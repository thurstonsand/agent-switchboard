// README's settings example, generated from the settings registry so it can't drift: `--check` fails when it has.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SETTINGS } from "../packages/cli/src/config.ts";

const START = "<!-- settings:start (generated by scripts/settings-readme.ts) -->";
const END = "<!-- settings:end -->";
const readme = join(import.meta.dir, "..", "README.md");

function block(): string {
	const lines: string[] = [];
	let table = "";
	// Top-level keys first: after a [table], a bare key belongs to it.
	const ordered = [...SETTINGS.filter((s) => s.key.length === 1), ...SETTINGS.filter((s) => s.key.length === 2)];
	for (const s of ordered) {
		if (s.example === null) continue;
		const [first, second] = s.key as [string, string | undefined];
		if (second !== undefined && first !== table) {
			table = first;
			lines.push("", `[${first}]`);
		}
		const value = Array.isArray(s.example) ? `[${s.example.map((v) => JSON.stringify(v)).join(", ")}]` : JSON.stringify(s.example);
		const assignment = `${second ?? first} = ${value}`;
		lines.push(s.note ? `${assignment.padEnd(25)} # ${s.note}` : assignment);
	}
	const example = `[[targets]]                 # the shortlist; without any, swb makes one from each harness's own
harness = "claude"          # "pi", "claude", or "codex"
model = "opus"
effort = "high"             # off, minimal, low, medium, high, xhigh, max, ultra, as the harness takes them
use = "Hard design and review" # a line for agents choosing among them
default = true              # what n opens on and agents get when they pick none; else the first

[[targets]]
harness = "pi"
provider = "openrouter"     # pi's targets name their provider
model = "moonshotai/kimi-k3"
effort = "low"

[[targets]]
harness = "claude"
agent = "Explore"           # Claude Code only: the whole session runs as this agent, on its model and effort`;
	return ["```toml", ...lines, "", example, "```"].join("\n");
}

const text = readFileSync(readme, "utf8");
const from = text.indexOf(START);
const to = text.indexOf(END);
if (from === -1 || to === -1) throw new Error(`README.md has no ${START} … ${END} block`);
const next = `${text.slice(0, from + START.length)}\n${block()}\n${text.slice(to)}`;
if (process.argv.includes("--check")) {
	if (next !== text) {
		console.error("README.md's settings block is out of date: run `mise run readme`");
		process.exit(1);
	}
} else writeFileSync(readme, next);
